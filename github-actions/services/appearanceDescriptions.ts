function result(path: string, title: string, description: string): AppearanceDescription {
  return { title, description, keywords: `${title} ${description} ${path}` }
}

export function describeAppearance(path: string): { title: string; description: string; keywords: string } {
  const keys: string[] = path.split('/').map((key: string): string => key.replace(/~1/g, '/').replace(/~0/g, '~'))
  const group: string = keys[0]
  const key: string = keys[1] ?? ''
  const exact: DescriptionSpec | undefined = fields[path]
  if (exact) return result(path, exact[0], exact[1])
  if (group === 'background' && (key === 'light' || key === 'dark') && /^[0-2]$/.test(keys[2] ?? '')) {
    const mode: string = key === 'light' ? '浅色' : '深色'
    const position: string = ['起始', '中间', '末尾'][Number(keys[2])]
    return result(path, `${mode}背景${position}色`, `用于${mode}模式默认背景渐变的第${Number(keys[2]) + 1}个色标及外观示例；改色会改变对应区域，透明色会透出下层。自绘背景优先，背景关闭时不显示默认渐变，不控制桌面小组件。`)
  }
  const numericScope: string | undefined = numeric[group]?.[key]
  if (numericScope !== undefined) {
    const labels: Record<string, string> = { fontSizes: '字号', spacing: '间距', sizes: '尺寸', radii: '圆角' }
    const effects: Record<string, string> = {
      fontSizes: '增大会放大文字或采用字号的图标，更易换行或截断；不改变小组件的系统文字样式。',
      spacing: '增大会扩大采用它的间距或内边距，零会取消该处留白；小组件布局字段通常直接用值，只有运行按钮内边距会再次查询此映射。',
      sizes: '增大会扩大图标、容器或分隔线；输入框为最小高度，实际仍可更高。不改变独立的小组件布局字号。',
      radii: '增大会使对应角更圆，零表示直角；宿主提供 rowCornerRadius 时可覆盖列表行与详情卡片圆角。',
    }
    return result(path, `${numericScope}（原${key}${labels[group]}）`, `影响范围：${numericScope}。此映射影响所有采用该原始值 ${key} 的 ${group} 调用点，不是只影响一个控件，也不会替换源码中所有同值数字。${effects[group]}`)
  }
  const color: DescriptionSpec | undefined = group === 'colors' ? colors[key] : undefined
  if (color) return result(path, `${color[0]}（${key}）`, `${color[1]}。替换色只影响读取此原颜色键的调用点；颜色键区分大小写。提高不透明度更实，降低会透出下层，需保持文字和背景可辨。`)
  const icon: DescriptionSpec | undefined = group === 'icons' ? icons[key] : undefined
  if (icon) return result(path, icon[0], `${icon[1]}；原符号「${key}」。替换为有效 SF Symbol 会改变所有采用此键的图标；不会改变操作、状态判定或图片内容，无效名称可能不显示。`)
  const location: string | undefined = group === 'text' ? textLocations[key] : undefined
  if (location !== undefined) return result(path, `文案「${key}」`, `原文「${key}」；位置：${location}。替换影响所有读取此原文键的调用点，不改业务数据或操作；长文本可能换行或截断，清空会隐藏对应文字。前后空格用于拼接时应保留。`)
  if (group === 'widget' && ['small', 'medium', 'large'].includes(key)) {
    const family: string = ({ small: '小号', medium: '中号', large: '大号' } as Record<string, string>)[key]
    const spec: DescriptionSpec | undefined = widgetFields[keys.slice(2).join('/')]
    if (spec) return result(path, `${family}小组件${spec[0]}`, `仅用于${family}尺寸。${spec[1]}。未配置提示不采用这套布局。`)
  }
  return result(path, `未识别的外观项（${keys.join(' / ')}）`, '当前说明表尚未收录此路径；请核对配置和实际引用后再调整，不能据此推定影响范围。')
}

